import Link from "next/link";
import { notFound } from "next/navigation";
import { prisma } from "@/lib/prisma";
import { formatSeconds } from "@/lib/paceEngine";
import { formatDateTime } from "@/lib/formatDate";
import type { ResolvedPaceSet } from "@/lib/generatePractice";
import { deletePracticeAction, saveAttendanceAction } from "../actions";
import { SubmitButton } from "@/components/SubmitButton";

export default async function PracticeDetailPage({
  params,
}: PageProps<"/practices/[practiceId]">) {
  const { practiceId } = await params;

  const practice = await prisma.practice.findUnique({
    where: { id: practiceId },
    include: {
      group: { include: { swimmers: { orderBy: { name: "asc" } } } },
      attendance: true,
    },
  });
  if (!practice) notFound();

  const paceSets: ResolvedPaceSet[] = practice.intervals ? JSON.parse(practice.intervals) : [];
  const attendanceBySwimmer = new Map(practice.attendance.map((a) => [a.swimmerId, a.present]));

  return (
    <div className="flex flex-col gap-6">
      <div className="flex items-start justify-between">
        <div>
          <h1 className="text-2xl font-semibold">
            {practice.group.name} — {practice.focus}
          </h1>
          <p className="text-slate-500 text-sm mt-1">
            {formatDateTime(practice.createdAt)} · generated by {practice.source}
          </p>
        </div>
        <div className="flex items-center gap-4">
          <Link href={`/groups/${practice.groupId}`} className="text-sm text-slate-600 hover:text-slate-900">
            ← Back to group
          </Link>
          <form action={deletePracticeAction}>
            <input type="hidden" name="practiceId" value={practice.id} />
            <button type="submit" className="text-sm text-red-600 hover:text-red-800">
              Delete
            </button>
          </form>
        </div>
      </div>

      <section className="rounded-lg border border-slate-200 bg-white p-5">
        <pre className="text-sm whitespace-pre-wrap font-mono text-slate-800">{practice.content}</pre>
      </section>

      <section className="rounded-lg border border-slate-200 bg-white p-5">
        <h2 className="font-medium text-slate-700 mb-1">Attendance</h2>
        <p className="text-xs text-slate-500 mb-3">
          Everyone defaults to present — just check off who wasn&apos;t here, then save.
        </p>
        {practice.group.swimmers.length === 0 ? (
          <p className="text-sm text-slate-500">No swimmers on this group&apos;s roster yet.</p>
        ) : (
          <form action={saveAttendanceAction} className="flex flex-col gap-3">
            <input type="hidden" name="practiceId" value={practice.id} />
            <input type="hidden" name="groupId" value={practice.groupId} />
            <div className="grid grid-cols-2 sm:grid-cols-3 gap-x-4 gap-y-2">
              {practice.group.swimmers.map((s) => {
                const present = attendanceBySwimmer.get(s.id) ?? true;
                return (
                  <label key={s.id} className="flex items-center gap-2 text-sm text-slate-700">
                    <input type="checkbox" name="absent" value={s.id} defaultChecked={!present} />
                    {s.name}
                  </label>
                );
              })}
            </div>
            <SubmitButton
              pendingText="Saving…"
              className="self-start bg-slate-800 text-white text-sm rounded-full px-4 py-1.5 hover:bg-slate-900 transition-colors"
            >
              Save attendance
            </SubmitButton>
          </form>
        )}
      </section>

      {paceSets.length > 0 && (
        <section className="flex flex-col gap-4">
          <h2 className="font-medium text-slate-700">Individual pace breakdown</h2>
          {paceSets.map((set, i) => (
            <div key={i} className="rounded-lg border border-slate-200 bg-white p-5">
              <h3 className="font-medium text-sm">{set.label}</h3>
              <p className="text-xs text-slate-500 mt-0.5">
                Same rep count and the exact same interval for every group — the slower group&apos;s distance
                per rep is shortened instead, so both groups go off the identical clock and finish in exactly
                the same total time.
              </p>
              <div className="mt-3 overflow-x-auto">
                <table className="w-full text-sm">
                  <thead>
                    <tr className="text-left text-slate-500 border-b border-slate-200">
                      <th className="py-1 pr-4">Swimmer</th>
                      <th className="py-1 pr-4">Group</th>
                      <th className="py-1 pr-4">Reps × Distance</th>
                      <th className="py-1 pr-4">Target</th>
                      <th className="py-1 pr-4">Interval</th>
                      <th className="py-1 pr-4">Set total</th>
                    </tr>
                  </thead>
                  <tbody>
                    {set.intervals
                      .slice()
                      .sort((a, b) => a.group.localeCompare(b.group) || a.targetTime - b.targetTime)
                      .map((iv) => {
                        const g = set.groupSets[iv.group];
                        return (
                          <tr key={iv.swimmerId} className="border-b border-slate-100 last:border-0">
                            <td className="py-1 pr-4">{iv.swimmerName}</td>
                            <td className="py-1 pr-4">
                              <span
                                className={`text-xs font-medium rounded px-1.5 py-0.5 ${
                                  iv.group === "A"
                                    ? "bg-teal-100 text-teal-700"
                                    : "bg-orange-100 text-orange-700"
                                }`}
                              >
                                {iv.group}
                              </span>
                            </td>
                            <td className="py-1 pr-4 text-slate-600">{g ? `${g.reps}x${g.distance}` : "—"}</td>
                            <td className="py-1 pr-4 text-slate-600">{formatSeconds(iv.targetTime)}</td>
                            <td className="py-1 pr-4 text-slate-600">on {formatSeconds(iv.interval)}</td>
                            <td className="py-1 pr-4 text-slate-600">
                              {g ? `~${formatSeconds(g.totalSeconds)}` : "—"}
                            </td>
                          </tr>
                        );
                      })}
                    {set.intervals.length === 0 && (
                      <tr>
                        <td colSpan={6} className="py-2 text-slate-500">
                          No swimmer times on file for this set.
                        </td>
                      </tr>
                    )}
                  </tbody>
                </table>
              </div>
            </div>
          ))}
        </section>
      )}
    </div>
  );
}

export const dynamic = "force-dynamic";
